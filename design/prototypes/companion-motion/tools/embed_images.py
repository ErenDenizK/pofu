"""Embed the art as WebP data URIs in pofu-hamster-data.js.

WebGL refuses image textures loaded from file:// URLs, so index.html reads
the art from this script instead. Run after changing either PNG.

Usage (from design/prototypes/companion-motion): python3 tools/embed_images.py
"""

import base64
import io
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent.parent


def data_uri(path: Path) -> str:
    buf = io.BytesIO()
    Image.open(path).save(buf, "WEBP", quality=90, alpha_quality=100, method=6)
    return "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode()


def main():
    js = (
        "// Generated by tools/embed_images.py from pofu-hamster.png and\n"
        "// pofu-hamster-lids.png. Data URIs let index.html run from file://.\n"
        f'window.POFU_IMAGE = "{data_uri(HERE / "pofu-hamster.png")}";\n'
        f'window.POFU_LID_PLATE = "{data_uri(HERE / "pofu-hamster-lids.png")}";\n'
    )
    (HERE / "pofu-hamster-data.js").write_text(js)
    print(f"pofu-hamster-data.js: {len(js) // 1024} KB")


if __name__ == "__main__":
    main()
